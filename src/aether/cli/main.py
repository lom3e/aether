def _cmd_init(args) -> None:
    name = args.name or Path.cwd().name
    target = Path(name) if args.name else Path.cwd()
    display_name = target.name

    if args.name and target.exists() and any(target.iterdir()):
        print(f"Error: Directory '{name}' is not empty.", file=sys.stderr)
        sys.exit(1)

    from aether.workspace.workspace import Workspace
    ws = Workspace.init(target, display_name)

    provider = args.provider or None       # no provider is assumed: without --provider the team is left unconfigured
    if not provider:
        model = None
    elif args.model:
        model = args.model
    elif provider == "openai":
        model = "gpt-4o"
    elif provider == "groq":
        model = "llama-3.3-70b-versatile"
    elif provider == "anthropic":
        model = "claude-3-5-sonnet-20241022"
    elif provider == "gemini":
        model = "gemini-1.5-pro"
    else:
        model = "llama3"
    provider_lines = (f"  provider: {provider}\n" + (f"  model: {model}\n" if model else "")) if provider else ""

    team_yaml = f"""# Aether Team Configuration
# Generated by: aether init

team:
  name: {display_name}
  knowledge: ../knowledge/
{provider_lines}
agents:
  - name: manager
    role: >
      You are the manager of this team. You receive tasks from the user,
      break them down, and delegate to the appropriate agents.
    relationships:
      - delegates_to: researcher

  - name: researcher
    role: >
      You are a research analyst. You gather information, search knowledge bases,
      and produce structured summaries for the manager.
    skills:
      - search_knowledge
"""

    readme = f"""# {display_name}

An Aether Workspace.

## Quick Start

1. **Add your knowledge documents:**
   ```
   aether knowledge add ./knowledge/
   ```

2. **Run a task:**
   ```
   aether run "Draft a research report about Apollo"
   ```
"""

    (ws.teams_dir / "default.yaml").write_text(team_yaml, encoding="utf-8")
    (target / "README.md").write_text(readme, encoding="utf-8")
    (ws.knowledge_dir / ".gitkeep").write_text("")

    print(f"✓ Aether Workspace initialized: {target.resolve()}")
    print()
    print("  Next steps:")
    print(f"    cd {target}")
    print(f"    # Drop documents into knowledge/")
    print(f"    aether knowledge add ./knowledge/")
    print(f"    aether run \"Your first task\"")
    if not provider:
        print("    # No AI provider chosen yet: pass --provider/--model to `aether run`, or set one in teams/default.yaml")


