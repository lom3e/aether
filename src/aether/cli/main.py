def _cmd_ui(args) -> None:
    import uvicorn
    import subprocess
    import threading
    import sys
    from pathlib import Path

    print("Starting Aether Workspace UI...")

    ui_dir = Path(__file__).parent.parent.parent.parent / "ui"
    if (ui_dir / "package.json").exists():
        print("Development mode detected. Starting Vite...")
        def start_vite():
            subprocess.run(["npm", "run", "dev"], cwd=ui_dir, stdout=subprocess.DEVNULL)
        threading.Thread(target=start_vite, daemon=True).start()
        print("UI available at http://localhost:5173")
    else:
        print("UI available at http://localhost:8000")
        import webbrowser
        threading.Timer(1.5, lambda: webbrowser.open("http://localhost:8000")).start()

    uvicorn.run("aether.server.app:app", host="0.0.0.0", port=8000, reload=True)

def _cmd_knowledge_add(args) -> None:
    path = Path(args.path)
    if not path.exists():
        print(f"Error: Path not found: {path}", file=sys.stderr)
        sys.exit(1)

    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    from aether.knowledge.store import KnowledgeStore
    from aether.knowledge.ingestion import DocumentIngester

    Path(kb_path).parent.mkdir(parents=True, exist_ok=True)

    store = KnowledgeStore(kb_path)
    ingester = DocumentIngester(store)

    count = ingester.ingest(path)
    after = store.count()

    print(f"✓ Indicizzati {count} chunk{'i' if count != 1 else ''} da {path}")
    print(f"  Totale knowledge base: {after} chunk{'i' if after != 1 else ''}")


def _cmd_knowledge_list(args) -> None:
    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    if not Path(kb_path).exists():
        print("Knowledge base vuota (nessun documento indicizzato).")
        return

    from aether.knowledge.store import KnowledgeStore
    store = KnowledgeStore(kb_path)
    sources = store.list_sources()

    if not sources:
        print("Knowledge base vuota.")
        return

    total = store.count()
    print(f"Knowledge base: {total} chunk{'i' if total != 1 else ''} da {len(sources)} sorgenti\n")
    for source in sources:
        chunks = store.get_by_source(source)
        print(f"  {source} ({len(chunks)} chunk{'i' if len(chunks) != 1 else ''})")


def _cmd_knowledge_clear(args) -> None:
    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    if not Path(kb_path).exists():
        print("Knowledge base già vuota.")
        return

    from aether.knowledge.store import KnowledgeStore
    store = KnowledgeStore(kb_path)
    count = store.count()
    store.clear()
    print(f"✓ Knowledge base svuotata ({count} chunk{'i' if count != 1 else ''} rimossi).")


def _cmd_knowledge_search(args) -> None:
    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    if not Path(kb_path).exists():
        print("Knowledge base vuota.")
        return

    from aether.knowledge.store import KnowledgeStore
    store = KnowledgeStore(kb_path)
    query = " ".join(args.query) if isinstance(args.query, list) else args.query
    results = store.search(query, limit=args.limit or 5)

    if not results:
        print(f"Nessun risultato per: {query!r}")
        return

    print(f"Risultati per {query!r} ({len(results)} chunk{'i' if len(results) != 1 else ''}):\n")
    for i, chunk in enumerate(results, 1):
        print(f"  [{i}] {chunk.source} (chunk {chunk.chunk_index})")
        preview = chunk.content[:200].replace("\n", " ")
        print(f"      {preview}...")
        print()


