def _ui_workspace_policy(args, cwd: Path, environ) -> tuple[str | None, str]:
    """
    Decides, BEFORE the server starts, which workspace selection `aether ui` allows.

    Selection order (implemented in aether.server.app.startup_event): AETHER_WORKSPACE, then the current directory
    when it holds an aether.yaml, then the last active workspace, then the first registered one. ``--data-dir`` only
    moves Aether's own data (registry, global config, new workspaces): it does NOT isolate a workspace found in the
    current directory. So a run that combines ``--data-dir`` with an implicit current-directory workspace is refused
    unless the user confirms it with ``--workspace``.

    Returns (workspace_path_to_export_or_None, human_readable_source). Raises SystemExit(2) on an unsafe/invalid request.
    """
    explicit = (getattr(args, "workspace", None) or "").strip()
    if explicit:
        root = Path(explicit).expanduser().resolve()
        if not (root / "aether.yaml").exists():
            print(f"Error: --workspace '{root}' is not an Aether workspace (no aether.yaml).", file=sys.stderr)
            raise SystemExit(2)
        return str(root), "--workspace"
    env_ws = (environ.get("AETHER_WORKSPACE") or "").strip()
    if env_ws:
        return None, "AETHER_WORKSPACE"
    data_dir = getattr(args, "data_dir", None)
    if data_dir and (cwd / "aether.yaml").exists():
        data_root = Path(data_dir).expanduser().resolve()
        cwd_root = cwd.resolve()
        if data_root != cwd_root and data_root not in cwd_root.parents:
            print(
                f"Error: the current directory '{cwd_root}' is an Aether workspace and would be opened as is, even "
                f"though --data-dir points elsewhere ('{data_root}'): --data-dir does not isolate it.\n"
                f"  - to use this workspace on purpose:  aether ui --workspace . --data-dir ...\n"
                f"  - to use a throw-away workspace:     aether ui --workspace /path/to/temp-workspace --data-dir /path/to/temp-data\n"
                f"  - or run the command from a directory that is not a workspace.",
                file=sys.stderr,
            )
            raise SystemExit(2)
    return None, "default selection"


def _cmd_ui(args) -> None:
    import uvicorn
    import socket
    import sys
    import threading
    import webbrowser
    from pathlib import Path
    from aether.core.paths import set_aether_data_dir
    from aether.server.app import app

    host = getattr(args, "host", None) or "127.0.0.1"
    port = getattr(args, "port", None)
    if port is None:
        port = 8000
    token = getattr(args, "token", None) or os.environ.get("AETHER_SESSION_TOKEN")
    insecure = getattr(args, "insecure_no_auth", False)
    if not token and not insecure:
        import secrets
        token = secrets.token_urlsafe(32)

    no_browser = getattr(args, "no_browser", False)
    data_dir = getattr(args, "data_dir", None)

    selected_ws, _ws_source = _ui_workspace_policy(args, Path.cwd(), os.environ)
    if selected_ws:
        os.environ["AETHER_WORKSPACE"] = selected_ws

    if data_dir:
        set_aether_data_dir(data_dir)
        os.environ["AETHER_DATA_DIR"] = str(Path(data_dir).expanduser().resolve())

    if token and not insecure:
        app.state.session_token = str(token).strip()
        os.environ["AETHER_SESSION_TOKEN"] = str(token).strip()
    elif insecure:
        app.state.session_token = None
        os.environ.pop("AETHER_SESSION_TOKEN", None)

    # Handle port 0 (ephemeral port allocation)
    bound_port = port
    sock = None
    if port == 0:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        sock.bind((host, 0))
        bound_port = sock.getsockname()[1]
        sock.listen(2048)

    app.state.bound_host = host
    app.state.bound_port = bound_port

    ui_dir = Path(__file__).parent.parent.parent.parent / "ui"
    if getattr(args, "dev", False) and (ui_dir / "package.json").exists() and not (ui_dir / "dist" / "index.html").exists():
        def start_vite():
            try:
                import subprocess
                subprocess.run(["npm", "run", "dev"], cwd=ui_dir, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            except Exception:
                pass
        threading.Thread(target=start_vite, daemon=True).start()

    base_url = f"http://{host}:{bound_port}"
    print("Starting Aether Workspace UI...")
    print(f"\n  ► Aether runtime ready at: {base_url}")
    if token and not insecure:
        print(f"  ► Session token (auth required): {token}")
    elif insecure:
        print("  ► WARNING: Running in insecure mode without API authentication (--insecure-no-auth).")
    print()
    sys.stdout.flush()

    if not no_browser and bound_port != 0 and port != 0:
        try:
            threading.Timer(1.2, lambda: webbrowser.open(base_url)).start()
        except Exception:
            pass

    config = uvicorn.Config(app, host=host, port=bound_port, reload=False, log_level="info")
    server = uvicorn.Server(config)
    app.state.uvicorn_server = server

    if sock is not None:
        server.run(sockets=[sock])
    else:
        server.run()


def _cmd_knowledge_add(args) -> None:
    path = Path(args.path)
    if not path.exists():
        print(f"Error: Path not found: {path}", file=sys.stderr)
        sys.exit(1)

    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    from aether.knowledge.store import KnowledgeStore
    from aether.knowledge.ingestion import DocumentIngester

    Path(kb_path).parent.mkdir(parents=True, exist_ok=True)

    store = KnowledgeStore(kb_path)
    ingester = DocumentIngester(store)

    count = ingester.ingest(path)
    after = store.count()

    print(f"✓ Indicizzati {count} chunk{'i' if count != 1 else ''} da {path}")
    print(f"  Totale knowledge base: {after} chunk{'i' if after != 1 else ''}")


def _cmd_knowledge_list(args) -> None:
    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    if not Path(kb_path).exists():
        print("Knowledge base vuota (nessun documento indicizzato).")
        return

    from aether.knowledge.store import KnowledgeStore
    store = KnowledgeStore(kb_path)
    sources = store.list_sources()

    if not sources:
        print("Knowledge base vuota.")
        return

    total = store.count()
    print(f"Knowledge base: {total} chunk{'i' if total != 1 else ''} da {len(sources)} sorgenti\n")
    for source in sources:
        chunks = store.get_by_source(source)
        print(f"  {source} ({len(chunks)} chunk{'i' if len(chunks) != 1 else ''})")


def _cmd_knowledge_clear(args) -> None:
    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    if not Path(kb_path).exists():
        print("Knowledge base già vuota.")
        return

    from aether.knowledge.store import KnowledgeStore
    store = KnowledgeStore(kb_path)
    count = store.count()
    store.clear()
    print(f"✓ Knowledge base svuotata ({count} chunk{'i' if count != 1 else ''} rimossi).")


def _cmd_knowledge_search(args) -> None:
    ws = _workspace_from_context()
    kb_path = ws.knowledge_db_path

    if not Path(kb_path).exists():
        print("Knowledge base vuota.")
        return

    from aether.knowledge.store import KnowledgeStore
    store = KnowledgeStore(kb_path)
    query = " ".join(args.query) if isinstance(args.query, list) else args.query
    results = store.search(query, limit=args.limit or 5)

    if not results:
        print(f"Nessun risultato per: {query!r}")
        return

    print(f"Risultati per {query!r} ({len(results)} chunk{'i' if len(results) != 1 else ''}):\n")
    for i, chunk in enumerate(results, 1):
        print(f"  [{i}] {chunk.source} (chunk {chunk.chunk_index})")
        preview = chunk.content[:200].replace("\n", " ")
        print(f"      {preview}...")
        print()


