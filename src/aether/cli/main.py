def _cmd_team_status(args) -> None:
    try:
        ws = _workspace_from_context()
        team = ws.load_team()
        config = team.config
    except Exception as exc:
        print(f"Error loading Workspace/Team: {exc}", file=sys.stderr)
        sys.exit(1)

    print(f"Team: {config.name}")
    print(f"Provider: {config.default_provider}" + (f" / {config.default_model}" if config.default_model else ""))
    if config.knowledge_path:
        print(f"Knowledge: {config.knowledge_path}")
    print()
    print(f"Agenti ({len(config.agents)}):")
    for agent in config.agents:
        delegations = agent.delegates_to()
        rel_str = f" → {', '.join(delegations)}" if delegations else ""
        print(f"  [{agent.name}] role={agent.role}{rel_str}")


