def _cmd_mcp(args) -> None:
    from aether.mcp.config import (
        format_client_snippet,
        merge_antigravity_config,
        revoke_antigravity_config,
    )
    from aether.mcp.server import AetherMCPServer
    from aether.workspace.registry import WorkspaceRegistry
    from aether.workspace.workspace import Workspace

    ws_identifier = getattr(args, "workspace", None)

    if getattr(args, "install_antigravity", False):
        target_ws = ws_identifier or "aether-acceptance-workspace"
        ok, msg = merge_antigravity_config(workspace_identifier=target_ws)
        if ok:
            print(f"✓ {msg}")
        else:
            print(f"✗ {msg}", file=sys.stderr)
            sys.exit(1)
        return

    if getattr(args, "uninstall_antigravity", False):
        ok, msg = revoke_antigravity_config()
        if ok:
            print(f"✓ {msg}")
        else:
            print(f"✗ {msg}", file=sys.stderr)
            sys.exit(1)
        return

    if getattr(args, "print_config", None):
        target_ws = ws_identifier or "aether-acceptance-workspace"
        print(format_client_snippet(client_type=args.print_config, workspace_identifier=target_ws))
        return

    # Default mode: run stdio MCP server for the authorized workspace
    resolved_ws = None
    if ws_identifier:
        p = Path(ws_identifier).expanduser()
        if p.exists() and (p / "aether.yaml").exists():
            resolved_ws = Workspace(p)
        else:
            for entry in WorkspaceRegistry.list_workspaces():
                if ws_identifier in (entry.get("id"), entry.get("name")):
                    resolved_ws = Workspace(Path(entry["path"]))
                    break
    if not resolved_ws:
        env_ws = os.environ.get("AETHER_WORKSPACE", "").strip()
        if env_ws:
            p = Path(env_ws).expanduser()
            if p.exists():
                resolved_ws = Workspace(p)
    if not resolved_ws:
        if (Path.cwd() / "aether.yaml").exists():
            resolved_ws = Workspace(Path.cwd())
    if not resolved_ws:
        for entry in WorkspaceRegistry.list_workspaces():
            if entry.get("is_active"):
                resolved_ws = Workspace(Path(entry["path"]))
                break
        if not resolved_ws:
            wss = WorkspaceRegistry.list_workspaces()
            if wss:
                resolved_ws = Workspace(Path(wss[0]["path"]))

    if not resolved_ws:
        print("Error: Could not resolve authorized Aether Workspace for MCP server.", file=sys.stderr)
        sys.exit(1)

    server = AetherMCPServer(workspace=resolved_ws)
    server.run_stdio()



