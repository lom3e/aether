def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="aether",
        description="Aether — runtime for persistent AI agent teams",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    # ---- init ----
    init_p = subparsers.add_parser("init", help="Scaffold a new team project")
    init_p.add_argument("name", nargs="?", help="Project directory name (default: current dir)")
    init_p.add_argument("--provider", choices=["openai", "anthropic", "ollama", "gemini", "groq"],
                        default="openai", help="Default AI provider")
    init_p.add_argument("--model", help="Default model name")

    # ---- run ----
    run_p = subparsers.add_parser("run", help="Run a task through the team")
    run_p.add_argument("task", nargs="+", help="Task description")
    run_p.add_argument("--provider", choices=["openai", "anthropic", "ollama", "gemini", "groq"],
                       help="Override provider")
    run_p.add_argument("--model", help="Override model")

    # ---- chat ----
    chat_p = subparsers.add_parser("chat", help="Start an interactive terminal chat with the workforce")
    chat_p.add_argument("--provider", choices=["openai", "anthropic", "ollama", "gemini", "groq"],
                        help="Override provider")
    chat_p.add_argument("--model", help="Override model")

    # ---- ui & serve ----
    ui_p = subparsers.add_parser("ui", help="Start the Aether Web UI / Desktop runtime")
    ui_p.add_argument("--host", default="127.0.0.1", help="Host address to bind (default: 127.0.0.1)")
    ui_p.add_argument("--port", type=int, default=8000, help="Port to listen on (use 0 for ephemeral port, default: 8000)")
    ui_p.add_argument("--data-dir", help="Root data directory for Aether configuration and workspaces")
    ui_p.add_argument("--token", help="Session token for local API and WebSocket authentication")
    ui_p.add_argument("--insecure-no-auth", action="store_true", help="Disable API session token authentication (INSECURE)")
    ui_p.add_argument("--workspace", help="Workspace directory to open (must contain aether.yaml); the only way to pick one explicitly together with --data-dir")
    ui_p.add_argument("--no-browser", action="store_true", help="Do not automatically launch a web browser window")
    ui_p.add_argument("--dev", action="store_true", help="Start frontend development server alongside backend")

    serve_p = subparsers.add_parser("serve", help="Alias for 'ui': Start the Aether Web API & runtime")
    serve_p.add_argument("--host", default="127.0.0.1", help="Host address to bind (default: 127.0.0.1)")
    serve_p.add_argument("--port", type=int, default=8000, help="Port to listen on (use 0 for ephemeral port, default: 8000)")
    serve_p.add_argument("--data-dir", help="Root data directory for Aether configuration and workspaces")
    serve_p.add_argument("--token", help="Session token for local API and WebSocket authentication")
    serve_p.add_argument("--insecure-no-auth", action="store_true", help="Disable API session token authentication (INSECURE)")
    serve_p.add_argument("--no-browser", action="store_true", help="Do not automatically launch a web browser window")
    serve_p.add_argument("--dev", action="store_true", help="Start frontend development server alongside backend")

    # ---- knowledge ----
    know_p = subparsers.add_parser("knowledge", help="Manage team knowledge base")
    know_sub = know_p.add_subparsers(dest="knowledge_command", required=True)

    know_add = know_sub.add_parser("add", help="Ingest documents")
    know_add.add_argument("path", help="File or directory to ingest")

    know_sub.add_parser("list", help="List indexed sources")
    know_sub.add_parser("clear", help="Remove all knowledge chunks")

    know_search = know_sub.add_parser("search", help="Search knowledge base")
    know_search.add_argument("query", nargs="+", help="Search query")
    know_search.add_argument("--limit", type=int, default=5, help="Max results")

    # ---- team ----
    team_p = subparsers.add_parser("team", help="Team management")
    team_sub = team_p.add_subparsers(dest="team_command", required=True)
    team_sub.add_parser("status", help="Show team status")

    # ---- agent ----
    agent_p = subparsers.add_parser("agent", help="Agent management")
    agent_sub = agent_p.add_subparsers(dest="agent_command", required=True)
    mem_p = agent_sub.add_parser("memory", help="Show agent memory")
    mem_p.add_argument("agent_name", help="Agent name")

    # ---- mcp ----
    mcp_p = subparsers.add_parser(
        "mcp",
        help="Start the Aether Model Context Protocol (MCP) server or configure integrations",
    )
    mcp_p.add_argument("--workspace", help="Authorized workspace ID, name, or directory path")
    mcp_p.add_argument("--install-antigravity", action="store_true", help="Register Aether MCP server in Google Antigravity config")
    mcp_p.add_argument("--uninstall-antigravity", action="store_true", help="Revoke Aether MCP server from Google Antigravity config")
    mcp_p.add_argument("--print-config", choices=["antigravity", "claude_desktop", "cursor"], help="Output client configuration snippet")

    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    dispatch = {
        "init": _cmd_init,
        "run": _cmd_run,
        "chat": _cmd_chat,
        "mcp": _cmd_mcp,
        "knowledge": {
            "add": _cmd_knowledge_add,
            "list": _cmd_knowledge_list,
            "clear": _cmd_knowledge_clear,
            "search": _cmd_knowledge_search,
        },
        "team": {
            "status": _cmd_team_status,
        },
        "agent": {
            "memory": _cmd_agent_memory,
        },
    }

    handler = dispatch.get(args.command)
    if callable(handler):
        handler(args)
    elif args.command in ("ui", "serve"):
        _cmd_ui(args)
    elif isinstance(handler, dict):
        sub_key = getattr(args, f"{args.command}_command", None)
        sub_handler = handler.get(sub_key) if sub_key else None
        if callable(sub_handler):
            sub_handler(args)
        else:
            parser.print_help()
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
