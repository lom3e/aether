# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        prog="aether",
        description="Aether — runtime for persistent AI agent teams",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    # ---- init ----
    init_p = subparsers.add_parser("init", help="Scaffold a new team project")
    init_p.add_argument("name", nargs="?", help="Project directory name (default: current dir)")
    init_p.add_argument("--provider", choices=["openai", "anthropic", "ollama", "gemini"],
                        default="openai", help="Default AI provider")
    init_p.add_argument("--model", help="Default model name")

    # ---- run ----
    run_p = subparsers.add_parser("run", help="Run a task through the team")
    run_p.add_argument("task", nargs="+", help="Task description")
    run_p.add_argument("--provider", choices=["openai", "anthropic", "ollama", "gemini"],
                       help="Override provider")
    run_p.add_argument("--model", help="Override model")

    # ---- ui ----
    ui_p = subparsers.add_parser("ui", help="Start the Aether Web UI")

    # ---- knowledge ----
    know_p = subparsers.add_parser("knowledge", help="Manage team knowledge base")
    know_sub = know_p.add_subparsers(dest="knowledge_command", required=True)

    know_add = know_sub.add_parser("add", help="Ingest documents")
    know_add.add_argument("path", help="File or directory to ingest")

    know_sub.add_parser("list", help="List indexed sources")
    know_sub.add_parser("clear", help="Remove all knowledge chunks")

    know_search = know_sub.add_parser("search", help="Search knowledge base")
    know_search.add_argument("query", nargs="+", help="Search query")
    know_search.add_argument("--limit", type=int, default=5, help="Max results")

    # ---- team ----
    team_p = subparsers.add_parser("team", help="Team management")
    team_sub = team_p.add_subparsers(dest="team_command", required=True)
    team_sub.add_parser("status", help="Show team status")

    # ---- agent ----
    agent_p = subparsers.add_parser("agent", help="Agent management")
    agent_sub = agent_p.add_subparsers(dest="agent_command", required=True)
    mem_p = agent_sub.add_parser("memory", help="Show agent memory")
    mem_p.add_argument("agent_name", help="Agent name")

    args = parser.parse_args()

    dispatch = {
        "init": _cmd_init,
        "run": _cmd_run,
        "knowledge": {
            "add": _cmd_knowledge_add,
            "list": _cmd_knowledge_list,
            "clear": _cmd_knowledge_clear,
            "search": _cmd_knowledge_search,
        },
        "team": {
            "status": _cmd_team_status,
        },
        "agent": {
            "memory": _cmd_agent_memory,
        },
    }

    handler = dispatch.get(args.command)
    if callable(handler):
        handler(args)
    elif args.command == "ui":
        _cmd_ui(args)
    elif isinstance(handler, dict):
        sub_key = getattr(args, f"{args.command}_command", None)
        sub_handler = handler.get(sub_key) if sub_key else None
        if callable(sub_handler):
            sub_handler(args)
        else:
            parser.print_help()
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
