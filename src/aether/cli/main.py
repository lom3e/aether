"""
Aether CLI — command-line interface for the Aether runtime.

Commands:
  aether init [name]              Scaffold a new team project
  aether run "task"               Run a task through the team (team.yaml)
  aether knowledge add <path>     Ingest documents into knowledge store
  aether knowledge list           List indexed knowledge sources
  aether knowledge clear          Remove all knowledge chunks
  aether knowledge search <q>     Search the knowledge base
  aether agent memory <name>      Show an agent's semantic memory facts
  aether team status              Show team agents and configuration
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path


def _workspace_from_context():
    """Resolve the workspace explicitly selected for CLI operations.

    Running from inside a workspace remains the default.  AETHER_WORKSPACE is
    supported for launchers and desktop integrations so the CLI cannot drift
    to the current directory when the application has already selected a
    workspace.
    """
    from aether.workspace.workspace import Workspace

    selected = os.environ.get("AETHER_WORKSPACE", "").strip()
    return Workspace(Path(selected).expanduser() if selected else Path.cwd())


# ---------------------------------------------------------------------------
# Init
# ---------------------------------------------------------------------------

def _cmd_init(args) -> None:
    name = args.name or Path.cwd().name
    target = Path(name) if args.name else Path.cwd()
    display_name = target.name

    if args.name and target.exists() and any(target.iterdir()):
        print(f"Error: Directory '{name}' is not empty.", file=sys.stderr)
        sys.exit(1)

    from aether.workspace.workspace import Workspace
    ws = Workspace.init(target, display_name)

    provider = args.provider or "openai"
    model = args.model or ("gpt-4o" if provider == "openai" else "llama3")

    team_yaml = f"""# Aether Team Configuration
# Generated by: aether init

team:
  name: {display_name}
  knowledge: ../knowledge/
  provider: {provider}
  model: {model}

agents:
  - name: manager
    role: >
      You are the manager of this team. You receive tasks from the user,
      break them down, and delegate to the appropriate agents.
    relationships:
      - delegates_to: researcher

  - name: researcher
    role: >
      You are a research analyst. You gather information, search knowledge bases,
      and produce structured summaries for the manager.
    skills:
      - search_knowledge
"""

    readme = f"""# {display_name}

An Aether Workspace.

## Quick Start

1. **Add your knowledge documents:**
   ```
   aether knowledge add ./knowledge/
   ```

2. **Run a task:**
   ```
   aether run "Draft a research report about Apollo"
   ```
"""

    (ws.teams_dir / "default.yaml").write_text(team_yaml, encoding="utf-8")
    (target / "README.md").write_text(readme, encoding="utf-8")
    (ws.knowledge_dir / ".gitkeep").write_text("")

    print(f"✓ Aether Workspace initialized: {target.resolve()}")
    print()
    print("  Next steps:")
    print(f"    cd {target}")
    print(f"    # Drop documents into knowledge/")
    print(f"    aether knowledge add ./knowledge/")
    print(f"    aether run \"Your first task\"")


